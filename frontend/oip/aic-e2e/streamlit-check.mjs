import { chromium } from 'playwright'
const OUT='D:/AI数字工厂-交付/_e2e_data/shots'
const sleep=ms=>new Promise(r=>setTimeout(r,ms))
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'})
const page=await browser.newPage({viewport:{width:1600,height:1000}})
const errors=[]; page.on('pageerror',e=>errors.push(String(e))); page.on('console',m=>{if(m.type()==='error') errors.push(m.text())})
await page.goto('http://127.0.0.1:8502',{waitUntil:'domcontentloaded'})
await page.waitForSelector('text=AIC FACTORY',{timeout:60000})
await sleep(3000)
await page.screenshot({path:`${OUT}/streamlit-01-overview.png`,fullPage:true})
async function go(label){
  const el=page.locator('label').filter({hasText:label}).first()
  await el.click({force:true})
  await sleep(3500)
}
await go('建模分析工作台')
await sleep(12000)
const iframe=page.locator('iframe[title="st.iframe"]').first()
console.log('iframe count', await page.locator('iframe').count())
if (await iframe.count()) console.log('iframe src', await iframe.getAttribute('src'))
console.log('workspace error text', await page.locator('text=页面渲染出现异常').count())
await page.screenshot({path:`${OUT}/streamlit-02-workspace.png`,fullPage:true})
await go('实验历史')
console.log('history page error text', await page.locator('text=页面渲染出现异常').count())
await page.screenshot({path:`${OUT}/streamlit-04-history.png`,fullPage:true})
await go('平台总览')
console.log('overview back', await page.locator('text=平台总览').count())
await page.screenshot({path:`${OUT}/streamlit-05-overview-back.png`,fullPage:true})
console.log('errors', errors.length, errors.slice(0,5))
await browser.close()
