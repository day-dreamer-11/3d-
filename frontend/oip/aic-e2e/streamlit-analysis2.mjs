import { chromium } from 'playwright'
const OUT='D:/AI数字工厂-交付/_e2e_data/shots'
const sleep=ms=>new Promise(r=>setTimeout(r,ms))
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'})
const page=await browser.newPage({viewport:{width:1600,height:1100}})
const errors=[]; page.on('pageerror',e=>errors.push(String(e))); page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
await page.goto('http://127.0.0.1:8502',{waitUntil:'domcontentloaded'})
await page.waitForSelector('text=AIC FACTORY',{timeout:60000}); await sleep(3000)
await page.locator('label').filter({hasText:'建模分析工作台'}).first().click({force:true}); await sleep(3500)
console.log('analysis metrics', await page.locator('text=瓶颈').count())
await page.getByRole('button',{name:'运行三种调度策略对比'}).click(); await sleep(8000)
await page.screenshot({path:`${OUT}/streamlit-11-edge-fixed.png`,fullPage:true})
await page.getByRole('button',{name:'生成并评估优化建议'}).click()
await page.waitForSelector('text=最佳候选',{timeout:180000}); await sleep(2500)
const best = await page.locator('text=最佳候选').first().innerText().catch(()=> '')
console.log('best', best)
await page.screenshot({path:`${OUT}/streamlit-12-optimize-fixed.png`,fullPage:true})
await page.getByRole('button',{name:'生成场景仿真报告'}).click()
await page.waitForSelector('text=报告已生成',{timeout:120000}); await sleep(1500)
await page.screenshot({path:`${OUT}/streamlit-13-report-fixed.png`,fullPage:true})
console.log('errors',errors.length,errors.slice(0,5))
await browser.close()
