import { chromium } from 'playwright'
const sleep=ms=>new Promise(r=>setTimeout(r,ms))
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'})
const page=await browser.newPage({viewport:{width:1600,height:1050}})
const errors=[];page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
await page.goto('http://127.0.0.1:8502',{waitUntil:'domcontentloaded'})
await page.waitForSelector('text=AIC FACTORY',{timeout:90000});await sleep(3500)
console.log('render-error',await page.locator('text=页面渲染出现异常').count())
const btn=page.getByRole('button',{name:/一键演示/}).first()
await btn.click()
await page.getByText(/一键演示：已在/).waitFor({timeout:120000})
console.log('notice', (await page.getByText(/一键演示：已在/).first().innerText()).slice(0,120))
await sleep(3000)
console.log('nav active', await page.locator('div[role="radiogroup"] label').filter({hasText:'建模分析工作台'}).first().getAttribute('data-baseweb'))
await page.screenshot({path:'D:/AI数字工厂-交付/_e2e_data/shots/one-click-demo.png',fullPage:true})
console.log('errors',errors.length,errors.slice(0,3))
await browser.close()
